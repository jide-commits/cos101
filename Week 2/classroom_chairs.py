# Displays number of rows and calculates total number of chairs

number_of_rows = int(input("Type the number of rows: "))
number_of_chairs_per_row = int(input("Type number of chairs per row: "))
total_chairs = number_of_rows * number_of_chairs_per_row

print("number of rows:", number_of_rows)
print("number of chairs per row:", number_of_chairs_per_row)
print("total chairs:", total_chairs)
